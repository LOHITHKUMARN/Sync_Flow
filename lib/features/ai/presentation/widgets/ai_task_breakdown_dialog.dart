import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:uuid/uuid.dart';
import '../../../../core/constants/app_colors.dart';
import '../../../tasks/domain/task_model.dart';
import '../../../tasks/domain/subtask_model.dart';
import '../../../tasks/presentation/task_providers.dart';
import '../ai_providers.dart';
import '../../domain/ai_action_result.dart';

class AiTaskBreakdownDialog extends ConsumerStatefulWidget {
  final TaskItem task;

  const AiTaskBreakdownDialog({super.key, required this.task});

  static Future<void> show(BuildContext context, TaskItem task) {
    return showDialog(
      context: context,
      builder: (_) => AiTaskBreakdownDialog(task: task),
    );
  }

  @override
  ConsumerState<AiTaskBreakdownDialog> createState() => _AiTaskBreakdownDialogState();
}

class _AiTaskBreakdownDialogState extends ConsumerState<AiTaskBreakdownDialog> {
  List<AiSubtaskSuggestion>? _suggestions;
  bool _isLoading = true;

  @override
  void initState() {
    super.initState();
    _loadSuggestions();
  }

  Future<void> _loadSuggestions() async {
    setState(() => _isLoading = true);
    final service = ref.read(aiAssistantServiceProvider);
    final result = await service.generateSubtasks(
      taskTitle: widget.task.title,
      taskDescription: widget.task.description,
    );
    if (mounted) {
      setState(() {
        _suggestions = result;
        _isLoading = false;
      });
    }
  }

  Future<void> _applySubtasks() async {
    final suggestions = _suggestions;
    if (suggestions == null) return;
    final selected = suggestions.where((s) => s.isSelected).toList();
    if (selected.isEmpty) {
      Navigator.pop(context);
      return;
    }

    final newSubtasks = List<TaskSubtask>.from(widget.task.subtasks);
    final now = DateTime.now();
    for (int i = 0; i < selected.length; i++) {
      newSubtasks.add(
        TaskSubtask(
          id: const Uuid().v4(),
          taskId: widget.task.id,
          title: selected[i].title,
          isCompleted: false,
          position: (newSubtasks.length + i + 1) * 1000.0,
          createdAt: now,
        ),
      );
    }

    final updatedTask = widget.task.copyWith(
      subtasks: newSubtasks,
      updatedAt: DateTime.now(),
    );

    await ref
        .read(tasksNotifierProvider(widget.task.projectId).notifier)
        .updateTaskDetails(updatedTask);

    if (mounted) {
      Navigator.pop(context);
      ScaffoldMessenger.of(context).showSnackBar(
        SnackBar(
          content: Text('✨ Added ${selected.length} AI-generated subtasks!'),
          behavior: SnackBarBehavior.floating,
        ),
      );
    }
  }

  @override
  Widget build(BuildContext context) {
    return AlertDialog(
      backgroundColor: AppColors.darkCard,
      shape: RoundedRectangleBorder(
        borderRadius: BorderRadius.circular(20),
        side: const BorderSide(color: AppColors.border),
      ),
      title: Row(
        children: [
          Container(
            padding: const EdgeInsets.all(8),
            decoration: BoxDecoration(
              color: AppColors.accent.withValues(alpha: 0.2),
              borderRadius: BorderRadius.circular(10),
            ),
            child: const Icon(Icons.auto_awesome_rounded, color: AppColors.accent, size: 20),
          ),
          const SizedBox(width: 12),
          const Expanded(
            child: Column(
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(
                  'AI Task Breakdown',
                  style: TextStyle(
                    color: AppColors.textPrimary,
                    fontSize: 16,
                    fontWeight: FontWeight.bold,
                  ),
                ),
                Text(
                  'Actionable checklist generated by SyncFlow AI',
                  style: TextStyle(
                    color: AppColors.textMuted,
                    fontSize: 11,
                  ),
                ),
              ],
            ),
          ),
        ],
      ),
      content: SizedBox(
        width: double.maxFinite,
        child: _isLoading
            ? const Padding(
                padding: EdgeInsets.symmetric(vertical: 36),
                child: Column(
                  mainAxisSize: MainAxisSize.min,
                  children: [
                    CircularProgressIndicator(strokeWidth: 2, color: AppColors.accent),
                    SizedBox(height: 16),
                    Text(
                      'Analyzing task requirements...',
                      style: TextStyle(color: AppColors.textSecondary, fontSize: 13),
                    ),
                  ],
                ),
              )
            : _suggestions == null || _suggestions!.isEmpty
                ? const Padding(
                    padding: EdgeInsets.all(24),
                    child: Text(
                      'No suggestions available.',
                      style: TextStyle(color: AppColors.textMuted),
                    ),
                  )
                : Column(
                    mainAxisSize: MainAxisSize.min,
                    crossAxisAlignment: CrossAxisAlignment.start,
                    children: [
                      Text(
                        'Select subtasks to add to "${widget.task.title}":',
                        style: const TextStyle(
                          color: AppColors.textSecondary,
                          fontSize: 13,
                        ),
                      ),
                      const SizedBox(height: 12),
                      Flexible(
                        child: ListView.builder(
                          shrinkWrap: true,
                          itemCount: _suggestions!.length,
                          itemBuilder: (ctx, idx) {
                            final item = _suggestions![idx];
                            return Container(
                              margin: const EdgeInsets.only(bottom: 8),
                              decoration: BoxDecoration(
                                color: item.isSelected
                                    ? AppColors.primary.withValues(alpha: 0.1)
                                    : AppColors.surface,
                                borderRadius: BorderRadius.circular(10),
                                border: Border.all(
                                  color: item.isSelected
                                      ? AppColors.primary.withValues(alpha: 0.5)
                                      : AppColors.border,
                                ),
                              ),
                              child: CheckboxListTile(
                                value: item.isSelected,
                                onChanged: (val) {
                                  setState(() => item.isSelected = val ?? false);
                                },
                                title: Text(
                                  item.title,
                                  style: TextStyle(
                                    color: AppColors.textPrimary,
                                    fontSize: 13,
                                    fontWeight: item.isSelected
                                        ? FontWeight.w600
                                        : FontWeight.normal,
                                  ),
                                ),
                                subtitle: Text(
                                  '~${item.estimatedMinutes} min estimated',
                                  style: const TextStyle(
                                    color: AppColors.textMuted,
                                    fontSize: 11,
                                  ),
                                ),
                                activeColor: AppColors.primary,
                                checkColor: Colors.white,
                                dense: true,
                                controlAffinity: ListTileControlAffinity.leading,
                                contentPadding: const EdgeInsets.symmetric(horizontal: 8),
                              ),
                            );
                          },
                        ),
                      ),
                    ],
                  ),
      ),
      actions: [
        TextButton(
          onPressed: () => Navigator.pop(context),
          child: const Text('Cancel', style: TextStyle(color: AppColors.textMuted)),
        ),
        if (!_isLoading && _suggestions != null)
          ElevatedButton.icon(
            onPressed: _applySubtasks,
            icon: const Icon(Icons.add_task_rounded, size: 16),
            label: Text(
              'Add (${_suggestions?.where((s) => s.isSelected).length ?? 0}) Subtasks',
              style: const TextStyle(fontWeight: FontWeight.bold, fontSize: 13),
            ),
            style: ElevatedButton.styleFrom(
              shape: RoundedRectangleBorder(borderRadius: BorderRadius.circular(10)),
              padding: const EdgeInsets.symmetric(horizontal: 16, vertical: 10),
            ),
          ),
      ],
    );
  }
}
